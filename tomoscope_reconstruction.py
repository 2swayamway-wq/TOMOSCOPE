"""TOMOSCOPE 2-D reconstruction module.

Reads the calibrated sinogram CSV produced by tomoscope_core.py and reconstructs
an approximate cross-section using:
  1. simple (unfiltered) backprojection, and
  2. filtered backprojection (FBP) with a ramp filter and optional Hann window.

The implementation is self-contained apart from NumPy and Matplotlib, both of
which are already dependencies of the capture application.

Coordinate convention
--------------------
The detector coordinate s increases from left to right.  Positive scan angles
are the clockwise rotation angles recorded by the capture application (when
viewed from above, with x to the right and y upwards).  This makes the Radon
coordinate relation s = x*cos(theta) + y*sin(theta).

This is an educational, parallel-beam reconstruction.  Camera-derived JPEG
measurements and the physical LED arrangement are approximate, so pixel values
must be treated as relative attenuation estimates, not calibrated CT numbers.
"""
from __future__ import annotations

import csv
import json
import math
import re
from dataclasses import dataclass
from datetime import datetime
from pathlib import Path

import numpy as np


ANGLE_HEADER_RE = re.compile(r"^attenuation_([+-]?(?:\d+(?:\.\d*)?|\.\d+))deg$", re.I)


@dataclass(frozen=True)
class SinogramData:
    """A sinogram with rows indexed by angle and columns by detector position."""

    detector_positions_cm: np.ndarray  # (n_detector,)
    angles_deg: np.ndarray             # (n_angles,)
    attenuation: np.ndarray            # (n_angles, n_detector)
    source_path: Path


@dataclass(frozen=True)
class ReconstructionResult:
    """Paths and dimensions for the generated reconstruction products."""

    output_dir: Path
    filtered_image_path: Path
    unfiltered_image_path: Path
    comparison_image_path: Path
    filtered_csv_path: Path
    unfiltered_csv_path: Path
    report_path: Path
    metadata_path: Path
    resolution: int
    projection_count: int
    detector_samples: int
    filter_name: str


def load_sinogram_csv(path: str | Path) -> SinogramData:
    """Read the exact CSV layout generated by the capture module.

    Expected header:
      detector_position_cm,attenuation_0deg,attenuation_10deg,...

    Each subsequent row contains one detector position followed by the
    attenuation at each angle.  The returned matrix is angle-major.
    """
    csv_path = Path(path).expanduser().resolve()
    if not csv_path.exists() or not csv_path.is_file():
        raise FileNotFoundError(f"Sinogram CSV not found: {csv_path}")

    try:
        with csv_path.open("r", newline="", encoding="utf-8-sig") as handle:
            reader = csv.reader(handle)
            header = next(reader, None)
            if not header or len(header) < 4:
                raise ValueError("The CSV needs one detector-position column and at least three angle columns.")

            first_name = header[0].strip().lower()
            if first_name not in {"detector_position_cm", "detector_position", "s_cm"}:
                raise ValueError(
                    "The first CSV column must be detector_position_cm. "
                    "Choose the sinogram_attenuation.csv created by TOMOSCOPE."
                )

            angles: list[float] = []
            for column_name in header[1:]:
                match = ANGLE_HEADER_RE.match(column_name.strip())
                if not match:
                    raise ValueError(
                        f"Unrecognised sinogram column '{column_name}'. "
                        "Expected names such as attenuation_0deg or attenuation_10deg."
                    )
                angles.append(float(match.group(1)))

            rows: list[list[float]] = []
            for line_number, row in enumerate(reader, start=2):
                if not row or all(not cell.strip() for cell in row):
                    continue
                if len(row) != len(header):
                    raise ValueError(
                        f"CSV row {line_number} has {len(row)} fields; expected {len(header)}."
                    )
                try:
                    rows.append([float(cell) for cell in row])
                except ValueError as exc:
                    raise ValueError(f"CSV row {line_number} contains a non-numeric value.") from exc
    except StopIteration as exc:
        raise ValueError("The selected CSV is empty.") from exc
    except OSError as exc:
        raise OSError(f"Could not read sinogram CSV: {exc}") from exc

    if len(rows) < 16:
        raise ValueError("The sinogram contains fewer than 16 detector samples; reconstruction would be unreliable.")

    values = np.asarray(rows, dtype=np.float64)
    if values.ndim != 2 or values.shape[1] != len(header):
        raise ValueError("The sinogram CSV has an inconsistent matrix shape.")

    detector = values[:, 0]
    attenuation = values[:, 1:].T  # (angles, detector samples)
    angle_array = np.asarray(angles, dtype=np.float64)

    if not np.all(np.isfinite(values)):
        raise ValueError("The sinogram contains NaN or infinite values. Recreate it from the photographs.")
    if np.any(np.diff(detector) <= 0):
        raise ValueError("Detector positions must increase from left to right.")
    if np.any(angle_array < 0) or np.any(angle_array >= 180):
        raise ValueError("Projection angles must be in the range 0° to less than 180°.")
    if np.unique(np.round(angle_array, 8)).size != angle_array.size:
        raise ValueError("The sinogram contains duplicate projection angles.")
    if attenuation.shape[0] < 3:
        raise ValueError("At least three projection angles are required.")

    # Sort angle columns, so externally reordered CSV columns are still safe.
    order = np.argsort(angle_array)
    angle_array = angle_array[order]
    attenuation = attenuation[order, :]

    detector_steps = np.diff(detector)
    step = float(np.median(detector_steps))
    if step <= 0 or not np.allclose(detector_steps, step, rtol=2e-3, atol=1e-8):
        raise ValueError("Detector positions are not uniformly spaced; the ramp-filter reconstruction requires uniform spacing.")

    return SinogramData(
        detector_positions_cm=detector,
        angles_deg=angle_array,
        attenuation=attenuation,
        source_path=csv_path,
    )


def _angular_weights_radians(angles_deg: np.ndarray) -> np.ndarray:
    """Cyclic angular quadrature weights for a full 180-degree scan.

    Parallel-beam projections are π-periodic with detector reversal.  Treating
    the angles cyclically gives each sample its midpoint/Voronoi angular width;
    for 0,10,...,170 degrees, each weight is exactly 10 degrees.
    """
    angles = np.asarray(angles_deg, dtype=np.float64)
    if angles.ndim != 1 or angles.size < 3:
        raise ValueError("At least three angles are required for angular integration.")
    gaps = np.diff(np.concatenate([angles, [angles[0] + 180.0]]))
    if np.any(gaps <= 0):
        raise ValueError("Projection angles must be strictly increasing and unique.")
    if np.max(gaps) > 3.0 * np.median(gaps):
        raise ValueError(
            "The angular scan has a large missing sector. Capture more evenly spaced projections before reconstructing."
        )
    weights = 0.5 * (np.roll(gaps, 1) + gaps)
    return np.deg2rad(weights)


def _next_power_of_two(value: int) -> int:
    return 1 << (int(value - 1).bit_length())


def _filter_sinogram(
    sinogram: np.ndarray,
    detector_spacing_cm: float,
    filter_name: str = "Hann",
) -> np.ndarray:
    """Apply a ramp filter to each projection using zero-padded FFTs."""
    matrix = np.asarray(sinogram, dtype=np.float64)
    n_angles, n_detector = matrix.shape
    if detector_spacing_cm <= 0:
        raise ValueError("Detector spacing must be positive.")

    # Padding to at least twice the detector length reduces circular FFT wraparound.
    n_fft = _next_power_of_two(2 * n_detector)
    pad_left = (n_fft - n_detector) // 2
    padded = np.zeros((n_angles, n_fft), dtype=np.float64)
    padded[:, pad_left:pad_left + n_detector] = matrix

    spectrum = np.fft.rfft(padded, axis=1)
    frequencies = np.fft.rfftfreq(n_fft, d=detector_spacing_cm)
    ramp = 2.0 * np.pi * np.abs(frequencies)
    nyquist = float(frequencies[-1])

    normalized_filter = filter_name.strip().lower()
    if normalized_filter in {"hann", "hann-windowed ramp", "hann window"}:
        window = 0.5 * (1.0 + np.cos(np.pi * np.abs(frequencies) / nyquist))
        window[np.abs(frequencies) > nyquist] = 0.0
        response = ramp * window
        display_name = "Hann-windowed Ram-Lak"
    elif normalized_filter in {"ram-lak", "ram lak", "unwindowed ramp"}:
        response = ramp
        display_name = "Ram-Lak (unwindowed)"
    elif normalized_filter in {"shepp-logan", "shepp logan"}:
        ratio = np.abs(frequencies) / (2.0 * nyquist)
        window = np.sinc(ratio)
        response = ramp * window
        display_name = "Shepp-Logan"
    else:
        raise ValueError("Unknown reconstruction filter. Choose Hann, Ram-Lak, or Shepp-Logan.")

    filtered_padded = np.fft.irfft(spectrum * response[None, :], n=n_fft, axis=1)
    filtered = filtered_padded[:, pad_left:pad_left + n_detector]
    if not np.all(np.isfinite(filtered)):
        raise ValueError("The projection filter produced invalid values.")
    return filtered


def reconstruct_arrays(
    data: SinogramData,
    resolution: int = 256,
    filter_name: str = "Hann",
) -> tuple[np.ndarray, np.ndarray, np.ndarray, np.ndarray, dict]:
    """Reconstruct unfiltered BP and filtered BP arrays.

    Returns (x_coordinates, y_coordinates, backprojection, filtered_backprojection, info).
    Array rows correspond to y increasing from bottom to top; columns correspond
    to x increasing from left to right.
    """
    if resolution < 64 or resolution > 1024:
        raise ValueError("Reconstruction resolution must be between 64 and 1024 pixels.")
    detector = np.asarray(data.detector_positions_cm, dtype=np.float64)
    sino = np.asarray(data.attenuation, dtype=np.float64)
    angles_deg = np.asarray(data.angles_deg, dtype=np.float64)

    if sino.shape != (angles_deg.size, detector.size):
        raise ValueError("Sinogram dimensions do not match the angle and detector coordinate arrays.")
    if np.any(sino < -1e-8):
        # Negative attenuation should not occur in the current capture code.
        raise ValueError("The sinogram contains negative attenuation values. Recreate the sinogram before reconstruction.")

    detector_spacing = float(np.median(np.diff(detector)))
    # The capture stage places the first/last detector sample at the entered
    # physical ROI boundaries, so their coordinate span is the reported width.
    detector_width = float(detector[-1] - detector[0])
    if detector_width <= 0:
        raise ValueError("Could not determine a positive detector field of view.")

    angle_weights = _angular_weights_radians(angles_deg)
    theta = np.deg2rad(angles_deg)
    filtered_sino = _filter_sinogram(sino, detector_spacing, filter_name)

    # Pixel-centre coordinates avoid placing pixels exactly on the detector boundary.
    x = np.linspace(-detector_width / 2 + detector_width / (2 * resolution),
                    detector_width / 2 - detector_width / (2 * resolution), resolution)
    y = np.linspace(-detector_width / 2 + detector_width / (2 * resolution),
                    detector_width / 2 - detector_width / (2 * resolution), resolution)
    xx, yy = np.meshgrid(x, y)

    backprojection = np.zeros((resolution, resolution), dtype=np.float64)
    filtered_backprojection = np.zeros_like(backprojection)

    # Each projection is interpolated onto the Radon coordinate
    # s = x*cos(theta) + y*sin(theta), then integrated over theta.
    for index, angle in enumerate(theta):
        sample_positions = xx * math.cos(float(angle)) + yy * math.sin(float(angle))
        flat_positions = sample_positions.ravel()
        projection = sino[index]
        filtered_projection = filtered_sino[index]

        sampled = np.interp(flat_positions, detector, projection, left=0.0, right=0.0)
        sampled_filtered = np.interp(
            flat_positions, detector, filtered_projection, left=0.0, right=0.0
        )
        weight = float(angle_weights[index])
        backprojection += sampled.reshape(backprojection.shape) * weight
        filtered_backprojection += sampled_filtered.reshape(backprojection.shape) * weight

    # A parallel-beam detector only supports the inscribed circular field of view.
    # Values outside it are not constrained by the available projection positions.
    radius = min(abs(detector[0]), abs(detector[-1]))
    valid_circle = (xx * xx + yy * yy) <= radius * radius
    backprojection[~valid_circle] = np.nan
    filtered_backprojection[~valid_circle] = np.nan

    info = {
        "projection_count": int(angles_deg.size),
        "detector_samples": int(detector.size),
        "detector_spacing_cm": detector_spacing,
        "detector_width_cm": detector_width,
        "field_of_view_radius_cm": radius,
        "resolution_pixels": int(resolution),
        "filter_name": filter_name,
        "angle_start_deg": float(angles_deg[0]),
        "angle_end_deg": float(angles_deg[-1]),
        "angular_weights_deg": np.rad2deg(angle_weights).tolist(),
        "coordinate_model": "s = x*cos(theta) + y*sin(theta)",
        "angle_convention": "Positive clockwise phantom rotation when viewed from above",
        "interpretation": "Relative camera-derived attenuation; not calibrated CT numbers",
    }
    return x, y, backprojection, filtered_backprojection, info


def _save_reconstruction_image(
    path: Path,
    image: np.ndarray,
    x: np.ndarray,
    y: np.ndarray,
    title: str,
    colourbar_label: str,
) -> None:
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    finite = image[np.isfinite(image)]
    if finite.size == 0:
        raise ValueError("Reconstruction contains no valid pixels inside the field of view.")
    vmin, vmax = np.percentile(finite, [1.0, 99.5])
    if not np.isfinite(vmin) or not np.isfinite(vmax) or abs(vmax - vmin) < 1e-12:
        vmin = float(np.min(finite))
        vmax = float(np.max(finite)) + 1e-9

    fig, ax = plt.subplots(figsize=(7.6, 7.0), constrained_layout=True)
    im = ax.imshow(
        image,
        origin="lower",
        extent=[float(x[0]), float(x[-1]), float(y[0]), float(y[-1])],
        cmap="magma",
        interpolation="nearest",
        vmin=vmin,
        vmax=vmax,
    )
    ax.set_title(title)
    ax.set_xlabel("x position (cm)")
    ax.set_ylabel("y position (cm)")
    ax.set_aspect("equal")
    fig.colorbar(im, ax=ax, label=colourbar_label, shrink=0.86)
    fig.savefig(path, dpi=190)
    plt.close(fig)


def _save_comparison(
    path: Path,
    unfiltered: np.ndarray,
    filtered: np.ndarray,
    x: np.ndarray,
    y: np.ndarray,
    filter_name: str,
) -> None:
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    fig, axes = plt.subplots(1, 2, figsize=(13, 6.2), constrained_layout=True)
    panels = [
        (axes[0], unfiltered, "Simple backprojection (blurred)"),
        (axes[1], filtered, f"Filtered backprojection ({filter_name})"),
    ]
    for ax, image, title in panels:
        finite = image[np.isfinite(image)]
        vmin, vmax = np.percentile(finite, [1.0, 99.5])
        if abs(vmax - vmin) < 1e-12:
            vmax = vmin + 1e-9
        im = ax.imshow(
            image,
            origin="lower",
            extent=[float(x[0]), float(x[-1]), float(y[0]), float(y[-1])],
            cmap="magma",
            interpolation="nearest",
            vmin=vmin,
            vmax=vmax,
        )
        ax.set_title(title)
        ax.set_xlabel("x position (cm)")
        ax.set_ylabel("y position (cm)")
        ax.set_aspect("equal")
        fig.colorbar(im, ax=ax, shrink=0.78, label="Relative reconstruction value")
    fig.suptitle("TOMOSCOPE — 2-D reconstruction comparison")
    fig.savefig(path, dpi=180)
    plt.close(fig)


def _write_image_csv(path: Path, x: np.ndarray, y: np.ndarray, image: np.ndarray) -> None:
    """Write a grid as a CSV whose rows are y positions and columns are x positions."""
    with path.open("w", newline="", encoding="utf-8-sig") as handle:
        writer = csv.writer(handle)
        writer.writerow(["y_position_cm"] + [f"x_{value:.6f}_cm" for value in x])
        for row_index, y_value in enumerate(y):
            row = image[row_index]
            writer.writerow([f"{y_value:.6f}"] + [
                "" if not np.isfinite(value) else f"{float(value):.10g}" for value in row
            ])


def reconstruct_sinogram_csv(
    sinogram_csv: str | Path,
    output_dir: str | Path | None = None,
    resolution: int = 256,
    filter_name: str = "Hann",
) -> ReconstructionResult:
    """Read a capture-stage sinogram and save all 2-D reconstruction outputs."""
    data = load_sinogram_csv(sinogram_csv)
    x, y, bp, fbp, info = reconstruct_arrays(data, resolution, filter_name)

    target_dir = Path(output_dir).expanduser().resolve() if output_dir else data.source_path.parent
    target_dir.mkdir(parents=True, exist_ok=True)

    filtered_png = target_dir / "reconstruction_filtered.png"
    unfiltered_png = target_dir / "reconstruction_unfiltered.png"
    comparison_png = target_dir / "reconstruction_comparison.png"
    filtered_csv = target_dir / "reconstruction_filtered.csv"
    unfiltered_csv = target_dir / "reconstruction_unfiltered.csv"
    report_path = target_dir / "reconstruction_report.txt"
    metadata_path = target_dir / "reconstruction_metadata.json"

    _save_reconstruction_image(
        filtered_png, fbp, x, y,
        "TOMOSCOPE — filtered backprojection reconstruction",
        "Relative reconstructed attenuation (approximate)",
    )
    _save_reconstruction_image(
        unfiltered_png, bp, x, y,
        "TOMOSCOPE — simple backprojection reconstruction",
        "Backprojected attenuation (blurred, approximate)",
    )
    _save_comparison(comparison_png, bp, fbp, x, y, info["filter_name"])
    _write_image_csv(filtered_csv, x, y, fbp)
    _write_image_csv(unfiltered_csv, x, y, bp)

    metadata = {
        "project": "TOMOSCOPE 2-D reconstruction",
        "created": datetime.now().isoformat(timespec="seconds"),
        "source_sinogram_csv": str(data.source_path),
        **info,
        "algorithm": "Parallel-beam filtered backprojection",
        "filter_description": (
            "Ramp filter multiplied by a Hann frequency window" if filter_name.lower().startswith("hann")
            else "Unwindowed ramp filter" if filter_name.lower().startswith("ram")
            else "Ramp filter multiplied by a Shepp-Logan frequency window"
        ),
        "limitations": [
            "The input sinogram comes from ordinary camera JPEG images and is not laboratory-calibrated.",
            "The reconstruction assumes parallel-beam geometry and a correctly centred rotation axis.",
            "The phantom must rotate clockwise when viewed from above for the stated coordinate orientation.",
            "A sparse set of projection angles produces streak artefacts and reduced spatial detail.",
            "Refraction, scattering, reflections, perspective, and camera auto-processing can violate the ideal model.",
            "The values are relative estimates and must not be interpreted as medical CT numbers.",
        ],
        "outputs": {
            "filtered_png": filtered_png.name,
            "unfiltered_png": unfiltered_png.name,
            "comparison_png": comparison_png.name,
            "filtered_csv": filtered_csv.name,
            "unfiltered_csv": unfiltered_csv.name,
            "report": report_path.name,
        },
    }
    metadata_path.write_text(json.dumps(metadata, indent=2), encoding="utf-8")

    report = [
        "TOMOSCOPE — 2-D RECONSTRUCTION REPORT",
        "=" * 58,
        f"Date: {metadata['created']}",
        f"Input sinogram: {data.source_path}",
        f"Projection views: {info['projection_count']}",
        f"Detector samples per view: {info['detector_samples']}",
        f"Detector field of view: {info['detector_width_cm']:.4f} cm",
        f"Detector sample spacing: {info['detector_spacing_cm']:.6f} cm",
        f"Reconstruction grid: {resolution} × {resolution} pixels",
        f"Pixel spacing: {info['detector_width_cm'] / resolution:.6f} cm/pixel",
        f"Projection angle range: {info['angle_start_deg']:.3f}° to {info['angle_end_deg']:.3f}°",
        f"Filter: {info['filter_name']}",
        "Algorithm: filtered backprojection (ramp filter + angular integration)",
        "Comparison: simple unfiltered backprojection is also saved for reference",
        "Coordinate relation: s = x cos(theta) + y sin(theta)",
        "Angle convention: positive clockwise phantom rotation when viewed from above",
        "",
        "INTERPRETATION AND LIMITATIONS",
        "The filtered image is an approximate 2-D attenuation map reconstructed from the sinogram.",
        "The unfiltered backprojection is expected to look blurrier; the ramp filter improves sharpness.",
        "Sparse angles can create streaks. More evenly spaced projections generally improve the result.",
        "The experiment uses camera JPEGs and approximate parallel-beam geometry; values are relative,",
        "not calibrated medical CT numbers. Centre the rotation axis on detector coordinate s = 0.",
        "Strong refraction, scattering, reflections, or sample movement can cause reconstruction artefacts.",
    ]
    report_path.write_text("\n".join(report) + "\n", encoding="utf-8")

    return ReconstructionResult(
        output_dir=target_dir,
        filtered_image_path=filtered_png,
        unfiltered_image_path=unfiltered_png,
        comparison_image_path=comparison_png,
        filtered_csv_path=filtered_csv,
        unfiltered_csv_path=unfiltered_csv,
        report_path=report_path,
        metadata_path=metadata_path,
        resolution=resolution,
        projection_count=info["projection_count"],
        detector_samples=info["detector_samples"],
        filter_name=info["filter_name"],
    )


if __name__ == "__main__":
    import argparse

    parser = argparse.ArgumentParser(description="Reconstruct a TOMOSCOPE sinogram CSV into a 2-D image.")
    parser.add_argument("sinogram_csv", help="Path to results/sinogram_attenuation.csv")
    parser.add_argument("--resolution", type=int, default=256, help="Square reconstruction grid size (64–1024).")
    parser.add_argument("--filter", dest="filter_name", choices=["Hann", "Ram-Lak", "Shepp-Logan"], default="Hann")
    parser.add_argument("--output", default=None, help="Optional output folder; defaults to the sinogram CSV folder.")
    args = parser.parse_args()

    result = reconstruct_sinogram_csv(
        args.sinogram_csv,
        output_dir=args.output,
        resolution=args.resolution,
        filter_name=args.filter_name,
    )
    print("Reconstruction complete.")
    print(f"Filtered image: {result.filtered_image_path}")
    print(f"Comparison image: {result.comparison_image_path}")
    print(f"Report: {result.report_path}")
